// 矢量小图标（只用矩形、圆、折线，保证各平台一致）
function icon(push, kind, x, y, s, color) {
  const c = color || '#ffffff';
  const u = s / 24;
  const R = (ax, ay, w, h, r, fill) => push({ t: 'rect', x: x + ax * u, y: y + ay * u, w: w * u, h: h * u, r: (r || 0) * u, fill: fill || c });
  const P = (pts, o) => push(Object.assign({ t: 'poly', pts: pts.map(([a, b]) => [x + a * u, y + b * u]) }, o));
  const C = (ax, ay, r, o) => push(Object.assign({ t: 'circle', x: x + ax * u, y: y + ay * u, r: r * u }, o));
  switch (kind) {
    case 'export': // 货箱 + 箭头
      R(2, 9, 11, 10, 1.5);
      P([[14, 14], [22, 14]], { color: c, lw: 2.4 * u });
      P([[18, 10], [22, 14], [18, 18]], { color: c, lw: 2.4 * u });
      break;
    case 'online': // 地球
      C(12, 12, 9, { stroke: c, lw: 2 * u });
      P([[3, 12], [21, 12]], { color: c, lw: 1.6 * u });
      P([[12, 3], [9, 8], [9, 16], [12, 21]], { color: c, lw: 1.6 * u });
      P([[12, 3], [15, 8], [15, 16], [12, 21]], { color: c, lw: 1.6 * u });
      break;
    case 'branch': // 办公楼
      R(5, 3, 14, 19, 1.5);
      for (let r = 0; r < 4; r++) for (let k = 0; k < 2; k++) R(8 + k * 5, 6 + r * 4, 3, 2, 0.5, 'rgba(15,23,42,0.55)');
      break;
    case 'factory': // 锯齿屋顶 + 烟囱
      P([[2, 22], [2, 12], [8, 8], [8, 12], [14, 8], [14, 12], [20, 8], [20, 22]], { fill: c });
      R(16, 3, 3, 7, 0.5);
      R(5, 15, 3, 3, 0.5, 'rgba(15,23,42,0.55)'); R(11, 15, 3, 3, 0.5, 'rgba(15,23,42,0.55)');
      break;
    case 'datacenter': // 服务器
      for (let r = 0; r < 3; r++) { R(4, 3 + r * 7, 16, 5.5, 1.2); C(7, 5.75 + r * 7, 1, { fill: 'rgba(15,23,42,0.6)' }); }
      break;
    case 'campaign': // 喇叭
      P([[3, 9], [9, 9], [18, 4], [18, 20], [9, 15], [3, 15]], { fill: c });
      R(6, 15, 3, 6, 1);
      break;
    case 'exit': // 返回箭头
      P([[20, 18], [20, 12], [6, 12]], { color: c, lw: 2.6 * u });
      P([[10, 7], [5, 12], [10, 17]], { color: c, lw: 2.6 * u });
      break;
    case 'hq': // 星
      P([[12, 2], [14.6, 9], [22, 9], [16, 13.6], [18.2, 21], [12, 16.6], [5.8, 21], [8, 13.6], [2, 9], [9.4, 9]], { fill: c });
      break;
    case 'news':
      R(3, 4, 18, 16, 2);
      R(6, 7, 12, 2.5, 0.5, 'rgba(15,23,42,0.6)'); R(6, 11, 7, 1.5, 0.5, 'rgba(15,23,42,0.45)'); R(6, 14, 9, 1.5, 0.5, 'rgba(15,23,42,0.45)');
      break;
    case 'book':
      P([[2, 5], [11, 7], [11, 21], [2, 19]], { fill: c });
      P([[22, 5], [13, 7], [13, 21], [22, 19]], { fill: c });
      break;
    case 'bulb':
      C(12, 10, 7, { fill: c });
      R(9, 16, 6, 5, 1.5);
      break;
    case 'road':
      P([[3, 21], [9, 3], [15, 3], [21, 21]], { fill: c });
      R(11, 5, 2, 3, 0.5, 'rgba(15,23,42,0.6)'); R(11, 10.5, 2, 3, 0.5, 'rgba(15,23,42,0.6)'); R(11, 16, 2, 3.5, 0.5, 'rgba(15,23,42,0.6)');
      break;
    case 'house':
      P([[3, 12], [12, 4], [21, 12]], { fill: c }); R(6, 12, 12, 9, 1); R(10, 15, 4, 6, 0.5, 'rgba(15,23,42,0.55)');
      break;
    case 'shop':
      R(3, 5, 18, 5, 1.5); R(4, 10, 16, 11, 1); R(7, 13, 4, 8, 0.5, 'rgba(15,23,42,0.55)'); R(13, 13, 5, 4, 0.5, 'rgba(15,23,42,0.45)');
      break;
    case 'bulldoze':
      P([[5, 5], [19, 19]], { color: c, lw: 3.2 * u }); P([[19, 5], [5, 19]], { color: c, lw: 3.2 * u });
      break;
    case 'hand':
      R(7, 9, 11, 11, 4); R(7, 4, 2.6, 9, 1.3); R(10.2, 3, 2.6, 9, 1.3); R(13.4, 3.5, 2.6, 9, 1.3); R(16.4, 5.5, 2.4, 8, 1.2); P([[7, 13], [4, 10], [3, 12], [7, 18]], { fill: c });
      break;
    case 'bolt':
      P([[13, 2], [5, 14], [11, 14], [9, 22], [19, 9], [13, 9]], { fill: c });
      break;
    case 'drop':
      P([[12, 3], [18, 13], [17, 18], [12, 21], [7, 18], [6, 13]], { fill: c });
      break;
    case 'flame':
      P([[12, 2], [18, 11], [17, 18], [12, 22], [7, 18], [6, 12], [9, 8], [10, 12]], { fill: c });
      break;
    case 'shield':
      P([[12, 2], [20, 5], [19, 14], [12, 22], [5, 14], [4, 5]], { fill: c });
      break;
    case 'cross':
      R(9, 3, 6, 18, 1.5); R(3, 9, 18, 6, 1.5);
      break;
    case 'cap':
      P([[2, 9], [12, 4], [22, 9], [12, 14]], { fill: c }); R(7, 11, 10, 6, 2); R(19, 9, 1.5, 7, 0.5);
      break;
    case 'tree':
      C(12, 9, 7, { fill: c }); R(11, 14, 2.4, 8, 0.8);
      break;
    case 'metro':
      R(3, 3, 18, 18, 4); P([[7, 17], [7, 7], [12, 13], [17, 7], [17, 17]], { color: 'rgba(15,23,42,0.75)', lw: 2.2 * u });
      break;
    case 'eye':
      P([[2, 12], [7, 6], [12, 4.5], [17, 6], [22, 12], [17, 18], [12, 19.5], [7, 18]], { fill: c }); C(12, 12, 3.6, { fill: 'rgba(15,23,42,0.7)' });
      break;
    case 'pause':
      R(6, 4, 4, 16, 1); R(14, 4, 4, 16, 1);
      break;
    case 'play':
      P([[7, 4], [19, 12], [7, 20]], { fill: c });
      break;
    case 'ff':
      P([[3, 5], [12, 12], [3, 19]], { fill: c }); P([[12, 5], [21, 12], [12, 19]], { fill: c });
      break;
    case 'plus':
      R(10.5, 4, 3, 16, 1); R(4, 10.5, 16, 3, 1);
      break;
    case 'minus':
      R(4, 10.5, 16, 3, 1);
      break;
    case 'coin': // ¥
      P([[6, 3], [12, 11], [18, 3]], { color: c, lw: 2.6 * u });
      R(10.7, 10, 2.6, 11, 1); R(6, 12, 12, 2.2, 1); R(6, 16, 12, 2.2, 1);
      break;
    default:
      C(12, 12, 8, { fill: c });
  }
}

module.exports = { icon };
